"""Regenerates the clients in src/ from the API descriptions listed in apis.yaml.

    uv run python scripts/generate.py           # from the committed specs in specs/
    uv run python scripts/generate.py --fetch   # download the latest specs first
    uv run python scripts/generate.py --only weather

Never edit generated code by hand: change apis.yaml, the name maps and pagination rules in
specs/, the auth class in src/noaa_apiroute/auth.py, or apiroute itself, then regenerate. The
Build workflow runs this with --fetch every week and commits whatever changes.
"""

import argparse
import json
import subprocess
import sys
from pathlib import Path

import httpx
import yaml

ROOT = Path(__file__).resolve().parent.parent
MARKER = "# Generated by scripts/generate.py from apis.yaml. Do not edit: regenerate instead."

# api.weather.gov refuses requests without a User-Agent naming the application
USER_AGENT = "noaa-apiroute (https://github.com/dougyouch/noaa-apiroute)"


def main() -> int:
    arguments = _parser().parse_args()
    config = yaml.safe_load((ROOT / "apis.yaml").read_text())
    apis = [api for api in config["apis"] if not arguments.only or api["name"] in arguments.only]
    if arguments.only and len(apis) != len(arguments.only):
        print(f"unknown API name in {arguments.only}", file=sys.stderr)
        return 1
    package_dir = ROOT / "src" / config["package"]
    for api in apis:
        spec = spec_path(api)
        if arguments.fetch:
            _fetch(api, spec)
        _generate(api, spec, package_dir)
    _write_group_packages(config, package_dir)
    _write_readme_table(config)
    return 0


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--fetch", action="store_true", help="download the latest specs first")
    parser.add_argument("--only", nargs="+", metavar="NAME", help="only these APIs (by name)")
    return parser


def spec_path(api: dict) -> Path:
    """specs/<name>.json, or .yaml for a spec published as YAML (kept as published)."""
    suffix = ".yaml" if api["spec"].endswith((".yaml", ".yml")) else ".json"
    if api["format"] == "wsdl":
        suffix = ".wsdl"
    return ROOT / "specs" / f"{api['name']}{suffix}"


def _fetch(api: dict, spec: Path) -> None:
    """Saves the spec as published. JSON is re-indented so that a reformatted upload doesn't
    show up as a change; key order is kept, since the generator follows it."""
    response = httpx.get(
        api["spec"], headers={"User-Agent": USER_AGENT}, follow_redirects=True, timeout=60
    )
    response.raise_for_status()
    if api["format"] == "openapi":
        text = _openapi_text(api, spec, response.text)
    else:
        text = response.text
        if "definitions" not in text[:2000]:
            raise ValueError(f"{api['name']}: {api['spec']} isn't a WSDL document")
    spec.parent.mkdir(exist_ok=True)
    spec.write_text(text)
    print(f"fetched {api['name']}")


def _openapi_text(api: dict, spec: Path, text: str) -> str:
    """The spec to save, after checking it is one: an HTML error page fails here, not later."""
    document = yaml.safe_load(text) if spec.suffix == ".yaml" else json.loads(text)
    if not isinstance(document, dict) or not ("openapi" in document or "swagger" in document):
        raise ValueError(f"{api['name']}: {api['spec']} isn't an OpenAPI document")
    if spec.suffix == ".yaml":
        return text
    return json.dumps(document, indent=2, ensure_ascii=False) + "\n"


def _generate(api: dict, spec: Path, package_dir: Path) -> None:
    out = package_dir.joinpath(*api["module"].split("."))
    command = [
        "apiroute",
        "generate",
        api["format"],
        str(spec),
        "-o",
        str(out),
        "--client-name",
        api["client"],
    ]
    if api.get("models", True):
        command.append("--models")
    if api.get("base_class"):
        command += ["--base-class", api["base_class"]]
    if api.get("base_url"):
        command += ["--base-url", api["base_url"]]
    if api.get("nullable_fields"):
        command.append("--nullable-fields")
    if api.get("open_enums"):
        command.append("--open-enums")
    if api.get("operation_names"):
        command += ["--operation-names", str(ROOT / api["operation_names"])]
    if api.get("pagination"):
        command += ["--pagination", str(ROOT / api["pagination"])]
    subprocess.run(command, check=True)


def _write_group_packages(config: dict, package_dir: Path) -> None:
    """Plain packages holding the generated clients, for modules nested one level down."""
    groups: dict[str, list[dict]] = {}
    for api in config["apis"]:
        parts = api["module"].split(".")
        if len(parts) > 1:
            groups.setdefault(parts[0], []).append(api)
    for group, apis in groups.items():
        listing = "\n".join(f"- {api['module']}: {api['title']}" for api in apis)
        (package_dir / group / "__init__.py").write_text(
            f'{MARKER}\n"""NOAA {group} APIs:\n\n{listing}\n"""\n'
        )


def _write_readme_table(config: dict) -> None:
    """The README's table of APIs, between its apis:start and apis:end markers."""
    readme = ROOT / "README.md"
    text = readme.read_text()
    start, end = "<!-- apis:start -->", "<!-- apis:end -->"
    if start not in text or end not in text:
        return
    rows = ["| API | Import | Docs |", "| --- | --- | --- |"]
    for api in config["apis"]:
        module = f"{config['package']}.{api['module']}"
        rows.append(
            f"| {api['title']} | `from {module} import {api['client']}` | [docs]({api['docs']}) |"
        )
    table = "\n".join(rows)
    before, rest = text.split(start, 1)
    after = rest.split(end, 1)[1]
    readme.write_text(f"{before}{start}\n{table}\n{end}{after}")


if __name__ == "__main__":
    sys.exit(main())
